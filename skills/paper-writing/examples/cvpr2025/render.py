"""Rebuild the example's vector figure and LaTeX values from the same CSV."""

import csv
import os
from decimal import Decimal
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build"
GROUPS = ("sequential", "batched", "reference")


def read_samples():
    samples = {group: [] for group in GROUPS}
    seen = set()
    with (ROOT / "materials/latency.csv").open(encoding="utf-8", newline="") as file:
        rows = csv.DictReader(file)
        if rows.fieldnames != ["sample_id", "group", "latency_ms"]:
            raise ValueError("Expected CSV columns sample_id,group,latency_ms")
        for row in rows:
            sample_id = row["sample_id"]
            group = row["group"]
            if not sample_id or sample_id in seen or group not in samples:
                raise ValueError(f"Invalid sample ID or group at CSV line {rows.line_num}")
            latency = Decimal(row["latency_ms"])
            if not latency.is_finite() or latency <= 0:
                raise ValueError(f"Expected positive latency at CSV line {rows.line_num}")
            samples[group].append(latency)
            seen.add(sample_id)
    if not all(samples.values()):
        raise ValueError("Expected at least one sample in each group")
    return samples


def display(value):
    return format(value, ".2f").rstrip("0").rstrip(".")


def main():
    samples = read_samples()
    means = {group: mean(values) for group, values in samples.items()}
    BUILD.mkdir(exist_ok=True)
    os.environ.setdefault("MPLCONFIGDIR", str(BUILD / "matplotlib"))

    import matplotlib

    matplotlib.use("Agg")
    from matplotlib import pyplot as plt
    from matplotlib.ticker import MaxNLocator

    with plt.rc_context({"font.size": 9, "pdf.fonttype": 42}):
        fig, ax = plt.subplots(figsize=(3.15, 1.6), layout="constrained")
        ax.barh([group.title() for group in GROUPS],
                [float(means[group]) for group in GROUPS],
                color="#c8dce8", height=0.6, zorder=2)
        for group, values in samples.items():
            ax.scatter([float(value) for value in values],
                       [group.title()] * len(values),
                       color="#174465", edgecolors="white", linewidths=0.5,
                       s=20, zorder=3)
        ax.set_xlim(left=0)
        ax.invert_yaxis()
        ax.set_xlabel("Latency per image (ms)")
        ax.xaxis.set_major_locator(MaxNLocator(6))
        ax.grid(axis="x", color="#dddddd", linewidth=0.5)
        for spine in ("top", "right", "left"):
            ax.spines[spine].set_visible(False)
        ax.tick_params(axis="y", length=0)
        fig.savefig(BUILD / "latency.pdf")
        plt.close(fig)

    macros = ["% Generated by render.py from materials/latency.csv."]
    for group in GROUPS:
        name = group.title()
        macros.extend([
            rf"\newcommand{{\{name}Count}}{{{len(samples[group])}}}",
            rf"\newcommand{{\{name}Mean}}{{{display(means[group])}}}",
        ])
    gap = display(means["sequential"] - means["batched"])
    macros.append(rf"\newcommand{{\SequentialMinusBatched}}{{{gap}}}")
    (BUILD / "metrics.tex").write_text("\n".join(macros) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
